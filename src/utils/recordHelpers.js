/** Audit / timestamp fields filled by SAP — not entered by user */
const SYSTEM_FIELD_NAMES = new Set([
  'CREATED_BY',
  'CREATED_AT',
  'CHANGED_BY',
  'CHANGED_AT',
  'ERNAM',
  'ERDAT',
  'ERZET',
  'AENAM',
  'AEDAT',
  'AEZET',
  'LAEDA'
])

function fieldName(field) {
  return field.field_name || field.FieldName
}

export function isSystemGeneratedField(field) {
  const name = fieldName(field).toUpperCase()
  if (SYSTEM_FIELD_NAMES.has(name)) return true
  if (/^(CREATED|CHANGED)_(BY|AT|ON|DATE|TIME)$/i.test(name)) return true
  return false
}

/** Keys (UUID) auto-generated on create */
export function isAutoGeneratedKeyField(field, mode) {
  const isKey = field.is_key || field.IsKeyField === 'X'
  const feType = field.fe_type || field.FeType
  return mode === 'create' && isKey && feType === 'uuid'
}

export function buildKeyRecord(allFields, values) {
  const keys = allFields.filter(f => f.is_key || f.IsKeyField === 'X')
  const keyData = {}
  keys.forEach(f => {
    const name = fieldName(f)
    keyData[name] = values[name] ?? values[f.FieldName]
  })
  return JSON.parse(formatPayload(keyData, keys, false))
}

export function buildKeyPayload(allFields, values) {
  const keys = allFields.filter(f => f.is_key || f.IsKeyField === 'X')
  const keyData = {}
  keys.forEach(f => {
    const name = fieldName(f)
    keyData[name] = values[name] ?? values[f.FieldName]
  })
  return formatPayload(keyData, keys, false)
}

function mergeFormIntoRecord(allFields, formValues, originalRow, isCreate) {
  const merged = {}
  allFields.forEach(f => {
    if (isSystemGeneratedField(f)) return

    const name = fieldName(f)
    const hidden = f.is_hidden || f.HiddenFlag === 'X'

    if (hidden) {
      merged[name] = originalRow?.[name] ?? originalRow?.[f.FieldName] ?? ''
      return
    }

    if (isCreate && (f.is_key || f.IsKeyField === 'X') && f.fe_type === 'uuid') {
      merged[name] = ''
      return
    }

    if (Object.hasOwn(formValues, name)) {
      merged[name] = formValues[name]
    } else if (Object.hasOwn(formValues, f.FieldName)) {
      merged[name] = formValues[f.FieldName]
    } else if (originalRow) {
      merged[name] = originalRow[name] ?? originalRow[f.FieldName] ?? ''
    } else {
      merged[name] = normalizeFieldValue(f, '')
    }
  })
  return merged
}

export function buildFullRecord(allFields, formValues, originalRow = null) {
  const isCreate = originalRow == null
  const merged = mergeFormIntoRecord(allFields, formValues, originalRow, isCreate)
  return JSON.parse(formatPayload(merged, allFields, isCreate))
}

export function buildFullRecordPayload(allFields, formValues, originalRow = null) {
  const isCreate = originalRow == null
  const merged = mergeFormIntoRecord(allFields, formValues, originalRow, isCreate)
  return formatPayload(merged, allFields, isCreate)
}

export function normalizeFieldValue(field, value) {
  const feType = field.fe_type || field.FeType
  if (feType === 'boolean' || field.FieldType === 'CHECK') {
    return value === true || value === 'X' ? 'X' : ''
  }
  if (feType === 'date' || field.FieldType === 'DATE') {
    return formatDateForSap(value)
  }
  return value ?? ''
}

export function validateMandatory(formFields, values) {
  return formFields
    .filter(f => f.is_mandatory || f.MandatoryFlag === 'X')
    .filter(f => {
      const feType = f.fe_type || f.FeType
      if (feType === 'boolean') return false
      const name = fieldName(f)
      const v = values[name] ?? values[f.FieldName]
      return v === undefined || v === null || String(v).trim() === ''
    })
    .map(f => f.label || f.LabelText || fieldName(f))
}

export function isFieldReadonly(field, mode) {
  if (field.ReadonlyFlag === 'X') return true
  const feType = field.fe_type || field.FeType
  if (feType === 'uuid' && mode === 'edit' && (field.is_key || field.IsKeyField === 'X')) {
    return true
  }
  return false
}

export function isDisplayOnlyField(field, mode) {
  return isFieldReadonly(field, mode)
}

const ETAG_FIELD_PRIORITY = ['CHANGED_AT', 'CHANGE_AT', 'LAST_CHANGED_AT']
const ETAG_FALLBACK_FIELDS = ['CREATED_AT', 'CREATED_ON', 'ERDAT']

export function isValidEtagValue(value) {
  if (value === 0 || value === '0') return false
  const formatted = formatEtagValueForAbap(value)
  if (formatted.length > 0) return true
  const s = String(value ?? '').trim()
  return s.length > 0 && s !== '0'
}

function fieldValuesEqual(field, a, b) {
  const name = fieldName(field).toUpperCase()
  const feType = field.fe_type || field.FeType
  if (
    feType === 'text' &&
    (ETAG_FIELD_PRIORITY.includes(name) || /^(CHANGED|CHANGE|LAST_CHANGED)_/i.test(name))
  ) {
    return String(a ?? '') === String(b ?? '')
  }
  if (field.FieldType === 'TIMESTAMP' || /_AT$/i.test(name)) {
    const fa = formatEtagValueForAbap(a)
    const fb = formatEtagValueForAbap(b)
    if (fa || fb) return fa === fb
    return String(a ?? '') === String(b ?? '')
  }
  return normalizeFieldValue(field, a) === normalizeFieldValue(field, b)
}

function pickEtagFromRow(allFields, row, fieldNames) {
  for (const name of fieldNames) {
    const f = allFields.find(x => fieldName(x) === name)
    const val = row?.[name]
    if (f && val !== undefined && val !== null && val !== '' && isValidEtagValue(val)) {
      return { field: name, value: val }
    }
  }
  return null
}

export function findEtagField(allFields, row) {
  if (!row || !allFields?.length) return { field: '', value: '' }

  const primary = pickEtagFromRow(allFields, row, ETAG_FIELD_PRIORITY)
  if (primary) return primary

  const fallback = pickEtagFromRow(allFields, row, ETAG_FALLBACK_FIELDS)
  if (fallback) return fallback

  for (const f of allFields) {
    if (f.is_key || f.IsKeyField === 'X') continue
    const name = fieldName(f)
    const val = row[name]
    if (/_AT$/i.test(name) && isValidEtagValue(val)) {
      return { field: name, value: val }
    }
  }

  return { field: '', value: '' }
}

function escapeRegex(s) {
  return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function findRecordBlockInDataJson(dataJson, recordKey) {
  if (!dataJson || !recordKey) return null

  const keys = Object.entries(recordKey)
  if (keys.length === 0) return null

  const [primaryKey, primaryVal] = keys[0]
  const anchor = new RegExp(
    `"${escapeRegex(primaryKey)}"\\s*:\\s*"${escapeRegex(String(primaryVal))}"`,
    'i'
  )
  const anchorMatch = anchor.exec(dataJson)
  if (!anchorMatch) return null

  const anchorIdx = anchorMatch.index
  const objStart = dataJson.lastIndexOf('{', anchorIdx)
  const objEnd = dataJson.indexOf('}', anchorIdx)
  if (objStart < 0 || objEnd <= objStart) return null

  const block = dataJson.slice(objStart, objEnd + 1)

  for (const [k, v] of keys.slice(1)) {
    const keyPattern = new RegExp(
      `"${escapeRegex(k)}"\\s*:\\s*"${escapeRegex(String(v))}"`,
      'i'
    )
    if (!keyPattern.test(block)) return null
  }

  return block
}

export function extractFieldFromDataJson(dataJson, recordKey, fieldName) {
  const block = findRecordBlockInDataJson(dataJson, recordKey)
  if (!block || !fieldName) return null

  const fieldMatch = block.match(
    new RegExp(
      `"${escapeRegex(fieldName)}"\\s*:\\s*("([^"]*)"|(\\d{4}-\\d{2}-\\d{2}\\s+\\d{2}:\\d{2}:\\d{2}\\.\\d+)|(\\d{14}\\.\\d+)|(\\d{14})|null|0)`,
      'i'
    )
  )
  if (!fieldMatch) return null

  if (fieldMatch[2] !== undefined) return fieldMatch[2]
  if (fieldMatch[3] !== undefined) return fieldMatch[3]
  if (fieldMatch[4] !== undefined) return fieldMatch[4]
  if (fieldMatch[5] !== undefined) {
    const d = fieldMatch[5]
    return `${d.slice(0, 4)}-${d.slice(4, 6)}-${d.slice(6, 8)} ${d.slice(8, 10)}:${d.slice(10, 12)}:${d.slice(12, 14)}.0000000`
  }
  return null
}

export function extractEtagFromDataJson(dataJson, recordKey, etagFieldName) {
  return extractFieldFromDataJson(dataJson, recordKey, etagFieldName)
}

export function buildRecordKeyString(allFields, row) {
  return JSON.stringify(buildKeyRecord(allFields, row))
}

export function buildEtagMap(dataJson, allFields, rows) {
  if (!dataJson || !allFields?.length || !rows?.length) return {}

  const map = {}
  for (const row of rows) {
    const recordKey = buildKeyRecord(allFields, row)
    const keyStr = buildRecordKeyString(allFields, row)
    const { field, value } = findEtagField(allFields, row)
    if (!field) continue

    const raw = extractEtagFromDataJson(dataJson, recordKey, field)
    if (raw !== null && raw !== undefined) {
      map[keyStr] = { field, value: String(raw) }
      continue
    }

    const formatted = formatEtagValueForAbap(value)
    if (formatted) {
      map[keyStr] = { field, value: formatted }
    } else if (value !== undefined && value !== null && String(value).trim() !== '') {
      map[keyStr] = { field, value: String(value) }
    }
  }
  return map
}

export function resolveEtagForUpdate(allFields, row, dataJson, recordKey, storedEtag = null) {
  if (storedEtag?.field && storedEtag?.value) {
    const raw = String(storedEtag.value).trim()
    if (raw && raw !== '0') {
      const formatted = formatEtagValueForAbap(raw)
      const value = formatted || raw
      return { field: storedEtag.field, value, candidates: [value] }
    }
    return { field: storedEtag.field, value: '', candidates: [] }
  }

  const { field, value } = findEtagField(allFields, row)
  if (!field) return { field: '', value: '', candidates: [] }

  if (dataJson && recordKey) {
    const raw = extractEtagFromDataJson(dataJson, recordKey, field)
    if (raw !== null && raw !== undefined && String(raw).trim() !== '' && raw !== '0') {
      const formatted = formatEtagValueForAbap(raw)
      const etagVal = formatted || String(raw)
      return { field, value: etagVal, candidates: [etagVal] }
    }
  }

  const formatted = formatEtagValueForAbap(value)
  if (!formatted && (value === undefined || value === null || String(value).trim() === '')) {
    return { field: '', value: '', candidates: [] }
  }

  const etagVal = formatted || String(value)
  return { field, value: etagVal, candidates: [etagVal] }
}

export function formatEtagForUpdate(
  allFields,
  row,
  dataJson = null,
  recordKey = null,
  storedEtag = null
) {
  return resolveEtagForUpdate(allFields, row, dataJson, recordKey, storedEtag)
}

