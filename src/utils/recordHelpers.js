export function getDirtyFieldNames(formFields, baselineRow, formValues) {
  if (!baselineRow) return []
  return formFields
    .filter(f => {
      const name = fieldName(f)
      const before = normalizeFieldValue(f, baselineRow[name] ?? baselineRow[f.FieldName])
      const after = normalizeFieldValue(f, formValues[name] ?? formValues[f.FieldName])
      return before !== after
    })
    .map(f => fieldName(f))
}

export function mergeRecordForConcurrentEdit(
  allFields,
  baselineRow,
  freshRow,
  formValues,
  dirtyFieldNames,
  dataJson = null,
  recordKey = null
) {
  const blocked = []
  const allowedChanges = {}

  for (const fieldNameKey of dirtyFieldNames) {
    const field = allFields.find(f => fieldName(f) === fieldNameKey)
    if (!field) continue

    const label = field.label || field.LabelText || fieldNameKey
    const key = fieldName(field)
    if (!fieldValuesEqual(field, baselineRow[key], freshRow[key])) {
      blocked.push({ fieldName: fieldNameKey, label })
      continue
    }

    allowedChanges[key] = normalizeFieldValue(
      field,
      formValues[key] ?? formValues[field.FieldName]
    )
  }

  const key = recordKey ?? buildKeyRecord(allFields, freshRow)
  const fullRecord = buildUpdateRecord(
    allFields,
    allowedChanges,
    freshRow,
    dataJson,
    key
  )

  return {
    fullRecord,
    blocked,
    hasChanges: Object.keys(allowedChanges).length > 0
  }
}

export function formatDeleteSummary(allFields, row) {
  const keys = allFields.filter(f => f.is_key || f.IsKeyField === 'X')
  if (keys.length === 0) {
    return Object.entries(row)
      .slice(0, 3)
      .map(([k, v]) => `${k}: ${v}`)
      .join(', ')
  }
  return keys
    .map(f => `${f.label || f.LabelText || fieldName(f)}: ${row[fieldName(f)] ?? ''}`)
    .join('\n')
}
